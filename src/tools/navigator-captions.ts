export function diagramCaption(id: string): string {
  if (captions[id]) return captions[id];
  if (id.startsWith("lock-"))
    return `Keep ${id.slice(5).replace("cornerAngle", "corner angle")} fixed`;
  if (id.startsWith("export-")) return `Save ${id.slice(7).toUpperCase()} geometry`;
  if (id.startsWith("selection-")) return "Refine highlighted faces, edges or bodies";
  if (id.startsWith("select-all-")) return `Select visible ${id.slice(11)}`;
  return "Choose a plane and draw editable curves";
}
