import { readFile, writeFile } from "node:fs/promises";

// These are deliberately public, type-only modules. Do not traverse model imports.
const modules = ["common", "tag", "decorator", "topology", "mesh-fit", "modeling"];
const declarations = [];
for (const name of modules) {
  const text = await readFile(
    new URL(`../src/agent-script/public/${name}.ts`, import.meta.url),
    "utf8",
  );
  const standalone = text.replace(/^import type\s+[\s\S]*?from "\.\/[^"\n]+";\n/gm, "");
  if (/^import\b|^export (?!interface\b|type\b)/m.test(standalone))
    throw new Error(`Public contract ${name} must contain only types and local type imports`);
  declarations.push(standalone.trim());
}
const text = declarations.join("\n\n");
const output = `// Generated by scripts/generate-script-types.mjs from agent-script/public.\nexport const scriptTypes = \`\n${text.replaceAll("`", "\\`").replaceAll("${", "\\${")}\n\`;\n`;
const path = new URL("../src/agent-cli/script-types.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== output)
    throw new Error("Script declarations are stale. Run npm run generate:script-types.");
} else await writeFile(path, output);
